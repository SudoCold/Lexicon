import {test,expect,_electron as electron,type ElectronApplication,type Page} from '@playwright/test';
import path from 'node:path';
import fs from 'node:fs/promises';
const root=process.cwd();
const data=path.join(root,'.test-data',`desktop-${Date.now()}`);
let app:ElectronApplication;let page:Page;
const errors:string[]=[];
async function open(){
  const env={...process.env,LEXICON_USER_DATA:data,LEXICON_TEST:'1'};delete env.ELECTRON_RUN_AS_NODE;
  app=await electron.launch({executablePath:process.env.LEXICON_EXECUTABLE,args:process.env.LEXICON_EXECUTABLE?[]:[root],env});page=await app.firstWindow();
  page.on('pageerror',e=>errors.push(e.message));
  await expect(page.locator('.page-heading h1')).toBeVisible();
}
test.afterAll(async()=>{await app?.close();});
test('complete desktop journey, offline storage, resuming, library, and backups',async()=>{
  await fs.mkdir(data,{recursive:true});await open();
  await page.screenshot({path:path.join(root,'.test-data','home.png'),fullPage:true});
  expect(await page.evaluate(()=>typeof window.lexicon?.load)).toBe('function');
  expect(await page.evaluate(()=>typeof (window as any).require)).toBe('undefined');
  await app.context().setOffline(true);
  await page.getByRole('button',{name:'Start a session',exact:true}).click();
  await expect(page.getByText('WHAT DOES THIS WORD MEAN?')).toBeVisible();
  const firstWord=await page.locator('.question-word h1').innerText();
  await page.getByRole('button',{name:/I don’t know this word/}).click();
  await expect(page.getByText('A new word for your world.')).toBeVisible();
  await expect(page.locator('.answer-option.correct')).toHaveCount(1);
  await page.screenshot({path:path.join(root,'.test-data','quiz.png'),fullPage:true});
  await expect.poll(async()=>await page.evaluate(async()=>((await window.lexicon!.load()) as any)?.active?.answers.length)).toBe(1);
  await app.close();await open();
  await page.getByRole('button',{name:'Continue session',exact:true}).click();
  await expect(page.locator('.question-word h1')).toHaveText(firstWord);
  await expect(page.getByText('A new word for your world.')).toBeVisible();
  await page.getByRole('button',{name:'Next word',exact:true}).click();
  await page.keyboard.press('1');
  await expect(page.locator('.answer-feedback')).toBeVisible();
  await page.getByRole('button',{name:'Next word',exact:true}).click();
  for(let i=2;i<10;i++){
    const state=await page.evaluate(async()=>await window.lexicon!.load()) as any;
    const id=state.active.wordIds[state.active.cursor];
    const bank=JSON.parse(await fs.readFile(path.join(root,'public/data/words.json'),'utf8'));
    const definition=bank.find((w:any)=>w.id===id).definition;
    await page.locator('.answer-option').filter({hasText:definition}).click();
    await expect(page.getByText('That’s the word. Nicely done.')).toBeVisible();
    await page.getByRole('button',{name:i===9?'See my results':'Next word',exact:true}).click();
  }
  await expect(page.getByRole('heading',{name:'A little wiser than before.'})).toBeVisible();
  await expect(page.locator('.result-word')).toHaveCount(10);
  await page.screenshot({path:path.join(root,'.test-data','results.png'),fullPage:true});
  await page.getByRole('button',{name:'Word library',exact:true}).click();
  await page.getByRole('textbox',{name:'Search words or definitions'}).fill('perspicacious');
  await expect(page.locator('.library-row')).toHaveCount(1);
  await page.getByRole('button',{name:'Save perspicacious',exact:true}).click();
  await page.getByRole('button',{name:'Saved',exact:true}).click();
  await expect(page.locator('.library-row')).toHaveCount(1);
  await page.locator('.library-word').click();
  await expect(page.getByRole('dialog')).toContainText('Quick to notice');
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await expect(page.getByText('Desktop edition · Progress saved in local SQLite')).toBeVisible();
  await page.getByRole('button',{name:'Dark',exact:true}).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
  await expect.poll(async()=>await page.evaluate(async()=>((await window.lexicon!.load()) as any)?.settings.theme)).toBe('dark');
  await page.getByRole('button',{name:'Light',exact:true}).click();
  await page.getByRole('button',{name:'My progress',exact:true}).click();
  await expect(page.locator('.history-row')).toHaveCount(1);
  await page.screenshot({path:path.join(root,'.test-data','progress.png'),fullPage:true});
  const saved=await page.evaluate(async()=>await window.lexicon!.load()) as any;
  expect(saved.history).toHaveLength(1);expect(saved.active).toBeNull();
  expect(Object.keys(saved.progress)).toHaveLength(10);
  expect(Object.values(saved.activity).reduce((a:number,v:any)=>a+v.answered,0)).toBe(10);
  expect(saved.bookmarks).toContain('adjective-perspicacious');
  const backup=path.join(data,'exported-backup.json');
  await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},backup);
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('button',{name:'Export',exact:true}).click();
  await expect(page.getByText('Your progress has been exported.')).toBeVisible();
  const exported=JSON.parse(await fs.readFile(backup,'utf8'));
  expect(exported.progress).toEqual(saved.progress);
  await page.getByRole('button',{name:'Reset progress',exact:true}).click();
  await page.getByRole('button',{name:'Keep my progress',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button',{name:'Reset progress',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Reset progress',exact:true}).click();
  await expect.poll(async()=>Object.keys(((await page.evaluate(()=>window.lexicon!.load())) as any).progress).length).toBe(0);
  await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},backup);
  await page.getByRole('button',{name:'Import',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('10 explored words');
  await page.getByRole('button',{name:'Replace with backup',exact:true}).click();
  await expect(page.locator('.page-heading h1')).toBeVisible();
  await expect.poll(async()=>Object.keys(((await page.evaluate(()=>window.lexicon!.load())) as any).progress).length).toBe(10);
  // An invalid import leaves the restored progress untouched.
  const invalid=path.join(data,'invalid-backup.json');await fs.writeFile(invalid,'{"version":999}');
  await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},invalid);
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('button',{name:'Import',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Could not import');
  expect(Object.keys(((await page.evaluate(()=>window.lexicon!.load())) as any).progress)).toHaveLength(10);
  const reviewState=await page.evaluate(()=>window.lexicon!.load()) as any;
  const dueId=Object.keys(reviewState.progress)[0];reviewState.progress[dueId].nextReview=Date.now()-1000;
  await page.evaluate(value=>window.lexicon!.save(value),reviewState);await page.reload();
  await expect(page.locator('.page-heading h1')).toBeVisible();
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:/Review words/}).click();
  await expect(page.getByRole('heading',{name:'1 word due for review'})).toBeVisible();
  await page.getByRole('button',{name:'Start review',exact:true}).click();
  await page.getByRole('button',{name:/I don’t know this word/}).click();
  await page.getByRole('button',{name:'Question unclear?',exact:true}).click();
  await page.getByRole('button',{name:'Hide question',exact:true}).click();
  await expect.poll(async()=>((await page.evaluate(()=>window.lexicon!.load())) as any).excluded).toContain(dueId);
  await page.getByRole('button',{name:'See my results',exact:true}).click();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('button',{name:'Restore',exact:true}).click();
  await expect.poll(async()=>((await page.evaluate(()=>window.lexicon!.load())) as any).excluded).toEqual([]);
  // Check the smallest supported desktop size and dark mode for overflow.
  await app.evaluate(({BrowserWindow})=>{BrowserWindow.getAllWindows()[0].setContentSize(960,720);});
  await page.getByRole('button',{name:'Dark',exact:true}).click();
  await page.getByRole('button',{name:'Overview',exact:true}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight)).toBe(true);
  const dark=await app.evaluate(async({BrowserWindow})=>(await BrowserWindow.getAllWindows()[0].capturePage()).toPNG().toString('base64'));
  await fs.writeFile(path.join(root,'.test-data','dark-small.png'),Buffer.from(dark,'base64'));
  expect(errors).toEqual([]);
});
